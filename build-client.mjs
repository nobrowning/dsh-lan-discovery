import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

const dictionaries = {};
for (const language of ['en', 'zh']) dictionaries[language] = JSON.parse(await readFile(new URL(`locale/${language}.json`, import.meta.url), 'utf8'));
assert.deepEqual(Object.keys(dictionaries.en).sort(), Object.keys(dictionaries.zh).sort(), 'Locale dictionaries must have identical keys.');
for (const key of Object.keys(dictionaries.en)) {
  const placeholders = text => [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort();
  for (const language of ['en', 'zh']) assert.ok(typeof dictionaries[language][key] === 'string' && dictionaries[language][key].trim(), `Missing ${language} translation: ${key}`);
  assert.deepEqual(placeholders(dictionaries.en[key]), placeholders(dictionaries.zh[key]), `Locale placeholders differ: ${key}`);
}
const source = await readFile(new URL('src/client.js', import.meta.url), 'utf8');
const marker = '/*__LAN_DICTIONARIES__*/';
assert.equal(source.split(marker).length, 2, 'Expected one dictionary bundle marker.');
const output = `/* Generated by build-client.mjs. Edit src/client.js and locale/*.json. */\n${source.replace(marker, `const dictionaries = ${JSON.stringify(dictionaries)};`)}`;
if (process.argv.includes('--check')) assert.equal(await readFile(new URL('client.js', import.meta.url), 'utf8'), output, 'The browser bundle is stale. Run npm run build.');
else await writeFile(new URL('client.js', import.meta.url), output);
